"""Three ways to hand the report a run, reduced to one protocol.

A run reaches the reporter as a live ``output/`` tree, as a ``.tar.zst`` /
``.tar.gz`` someone downloaded from CI, or as a directory an earlier ``tar -xf``
left behind. Downstream code must not care which — so everything here exists to
produce one :class:`ReportSource` with a validated manifest and a single way to
ask for bytes.

Two decisions carry this module.

**The manifest is the whole index.** ``bundle/classify.py`` already stamped
``scenario``/``locale``/``layout``/``step``/``frame`` onto every file when the
bundle was created, so the reporter never parses a path. That is the same
"one grammar, one home" rule the capture layer follows, applied to the manifest.

**Archives are read in two passes, and neither pass is wasteful.** Pass 1 is
``inspect_bundle``, which streams until it meets ``manifest.json`` and stops —
a few kilobytes, and it makes no assumption about member position. Pass 2 pulls
exactly what the caller asked for. Two passes rather than one because the zstd
stream is non-seekable (``tarfile`` ``r|``): there is no rewinding to fetch
something a single pass decided about too late.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from ..contracts.bundle import BundleManifest, parse_manifest

#: Names of the two source kinds that come with their own bytes on disk.
KIND_TREE = "tree"
KIND_ARCHIVE = "archive"
KIND_DIR = "dir"

MANIFEST_NAME = "manifest.json"

_ARCHIVE_SUFFIXES = (".zst", ".gz")


class ReportSourceError(Exception):
    """The input could not be read as a run. Fatal, and always actionable."""


@dataclass
class ReportSource:
    """A run's manifest plus one way to fetch the bytes behind it."""

    manifest: BundleManifest
    kind: str
    origin: Path
    label: str
    warnings: list[str] = field(default_factory=list)
    #: Live-tree mode only: manifest path → local file, from ``plan.members()``.
    _local: dict[str, Path] = field(default_factory=dict, repr=False)
    #: Live-tree mode only: manifest path → generated bytes (junit.xml).
    _inline: dict[str, bytes] = field(default_factory=dict, repr=False)

    @property
    def is_live_tree(self) -> bool:
        """True when the bytes are the project's own ``output/``.

        The one place this matters is coverage: reading the local
        ``.steppy/coverage.db`` for someone *else's* downloaded bundle would
        attribute this machine's coverage map to their run, and produce a
        plausible-looking percentage that means nothing.
        """
        return self.kind == KIND_TREE

    def fetch(
        self,
        *,
        into: Optional[dict[str, Path]] = None,
        texts: Optional[set[str]] = None,
    ) -> tuple[dict[str, bytes], list[str]]:
        """Copy/return the requested members. ``(fetched_texts, warnings)``.

        ``into`` maps a manifest path to the file it should land in; ``texts``
        names manifest paths wanted as bytes. Callers choose every destination
        themselves — a path out of a downloaded manifest is untrusted input and is
        never used to decide where anything is written.
        """
        wanted_files = dict(into or {})
        wanted_texts = set(texts or ())
        if self.kind == KIND_ARCHIVE:
            from ..bundle.archive import ArchiveError, read_members

            try:
                return read_members(self.origin, into=wanted_files, texts=wanted_texts)
            except ArchiveError as e:
                raise ReportSourceError(str(e)) from e
        return self._fetch_local(wanted_files, wanted_texts)

    def _fetch_local(self, wanted_files: dict[str, Path], wanted_texts: set[str]) -> tuple[dict[str, bytes], list[str]]:
        import shutil

        fetched: dict[str, bytes] = {}
        warnings: list[str] = []
        for name in sorted(set(wanted_files) | wanted_texts):
            payload = self._inline.get(name)
            source = self._local.get(name)
            target = wanted_files.get(name)
            if payload is None and (source is None or not source.is_file()):
                warnings.append(f"{name} is listed in the manifest but missing on disk")
                continue
            if name in wanted_texts:
                data = payload if payload is not None else source.read_bytes()
                fetched[name] = data
                if target is not None:
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(data)
                continue
            target.parent.mkdir(parents=True, exist_ok=True)
            if payload is not None:
                target.write_bytes(payload)
            else:
                shutil.copy2(source, target)
        return fetched, warnings


def open_source(
    path: Optional[Path],
    *,
    project_root: Path,
    output_dir: Optional[Path] = None,
    run_id: Optional[str] = None,
) -> ReportSource:
    """Resolve *path* to a :class:`ReportSource`.

    ``None`` means the project's live ``output/`` tree — the case a CI job hits
    right after ``steppy run --bundle``, and the only one where a local coverage
    store may be consulted.
    """
    if path is None:
        return _from_tree(project_root=project_root, output_dir=output_dir, run_id=run_id)
    path = Path(path)
    if path.is_dir():
        return _from_dir(path)
    if not path.exists():
        raise ReportSourceError(f"no such bundle or directory: {path}")
    if path.suffix in _ARCHIVE_SUFFIXES:
        return _from_archive(path)
    raise ReportSourceError(
        f"{path.name} is neither a .tar.zst/.tar.gz bundle nor an unpacked bundle directory. "
        "Pass a bundle, a directory containing manifest.json, or nothing at all to report on ./output/."
    )


def _from_tree(*, project_root: Path, output_dir: Optional[Path], run_id: Optional[str]) -> ReportSource:
    from ..bundle import BundleError, plan_bundle

    try:
        plan = plan_bundle(project_root=project_root, output_dir=output_dir, run_id=run_id)
    except BundleError as e:
        raise ReportSourceError(str(e)) from e

    local: dict[str, Path] = {}
    inline: dict[str, bytes] = {}
    for member in plan.members():
        if member.arcname == MANIFEST_NAME:
            continue
        if member.data is not None:
            inline[member.arcname] = member.data
        elif member.source is not None:
            local[member.arcname] = member.source

    tree = output_dir or (project_root / "output")
    return ReportSource(
        manifest=plan.manifest,
        kind=KIND_TREE,
        origin=tree,
        # Project-relative, because this string is written into ``report.json`` and
        # rendered into the page footer — and both get published. An absolute path
        # leaks a home directory and a CI runner's layout to anyone who opens the
        # site, which is a small thing that is impossible to take back.
        label=_display_path(tree, project_root),
        warnings=list(plan.manifest.warnings),
        _local=local,
        _inline=inline,
    )


def _from_archive(path: Path) -> ReportSource:
    from ..bundle import BundleError, inspect_bundle

    try:
        manifest = inspect_bundle(path)
    except BundleError as e:
        raise ReportSourceError(str(e)) from e
    return ReportSource(
        manifest=manifest,
        kind=KIND_ARCHIVE,
        origin=path,
        label=path.name,
        warnings=list(manifest.warnings),
    )


def _display_path(path: Path, root: Path) -> str:
    """A path safe to publish: relative to *root* when it is under it, else a name.

    Never the absolute path. Falling back to the basename rather than the full path
    keeps the guarantee even for a tree outside the project (``--output-dir``
    somewhere else), where "relative" is not available.
    """
    try:
        return Path(path).resolve().relative_to(Path(root).resolve()).as_posix()
    except (OSError, ValueError):
        return Path(path).name


def _from_dir(path: Path) -> ReportSource:
    manifest_path = path / MANIFEST_NAME
    if not manifest_path.is_file():
        raise ReportSourceError(
            f"{path} contains no {MANIFEST_NAME} — is it an unpacked bundle? "
            "(a bundle unpacks to manifest.json + junit.xml + events/ + output/)"
        )
    try:
        manifest = parse_manifest(json.loads(manifest_path.read_text(encoding="utf-8")))
    except (OSError, ValueError) as e:
        raise ReportSourceError(f"could not read {manifest_path}: {e}") from e

    # An unpacked bundle holds every member at its manifest path, relative to the
    # directory — which is exactly why the bundle refuses to rewrite paths.
    local = {entry.path: path / entry.path for entry in manifest.files}
    return ReportSource(
        manifest=manifest,
        kind=KIND_DIR,
        origin=path,
        # Basename only, like the archive's — an unpacked bundle sits wherever
        # someone happened to untar it, and that path goes into a published file.
        label=path.name,
        warnings=list(manifest.warnings),
        _local=local,
    )
